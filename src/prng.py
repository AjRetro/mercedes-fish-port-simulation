# src/prng.py
"""
Pseudo-Random Number Generation (PRNG) Engine
Implemented strictly in accordance with Discrete-Event Simulation & Maritime Queueing Standards.

Theoretical Foundations:
1. Linear Congruential Generator (LCG) / Multiplicative Congruential Generator (MCG):
   X_{n+1} = (a * X_n + c) mod m
2. Prime Modulus with Mersenne Prime:
   M_31 = 2^31 - 1 = 2,147,483,647
3. Hull-Dobell Theorem (Mixed LCG):
   Full period m iff gcd(c, m) = 1, a = 1 (mod p) for all prime p|m, and a = 1 (mod 4) if 4|m.
4. Primitive Root Theorem (Multiplicative LCG where c = 0):
   Period m - 1 when m is prime and a is a primitive root of m.
   M_31 - 1 = 2 * 3^2 * 7 * 11 * 31 * 151 * 331
   Primitive root a = 7^5 = 16,807 (Park-Miller classic) and a = 7^13 = 252,246,292 mod M_31.
5. Common Random Numbers (CRN) & Stream Splitting:
   Independent non-overlapping streams for arrivals, cargo sizing, and operations.
"""

import math
from typing import Dict, List, Tuple


class LehmerLCG:
    """
    Lehmer / Multiplicative Congruential Generator (MCG)
    X_{n+1} = (a * X_n) mod m
    Default parameters: Mersenne prime M31 = 2^31 - 1, Multiplier a = 16807 (Park-Miller).
    """
    MERSENNE_PRIME_31: int = 2147483647  # 2^31 - 1
    PARK_MILLER_A: int = 16807           # 7^5
    ALTERNATIVE_A: int = 252246292       # 7^13 mod M31

    def __init__(self, seed: int = 123456789, a: int = PARK_MILLER_A, m: int = MERSENNE_PRIME_31):
        if m <= 0:
            raise ValueError("Modulus m must be positive.")
        if not (0 < seed < m):
            raise ValueError(f"Seed must satisfy 0 < seed < {m}")
        if not (1 < a < m):
            raise ValueError(f"Multiplier 'a' must satisfy 1 < a < {m}")
        
        self.m = m
        self.a = a
        self.c = 0
        self.initial_seed = seed
        self.state = seed

    def next_int(self) -> int:
        """Advance the generator state and return the next integer."""
        self.state = (self.a * self.state) % self.m
        return self.state

    def next_uniform(self) -> float:
        """Return a continuous pseudo-random uniform variate U in (0, 1)."""
        return self.next_int() / self.m

    def reset(self):
        """Reset the generator back to its initial seed."""
        self.state = self.initial_seed

    @classmethod
    def verify_primitive_root(cls, a: int = PARK_MILLER_A, m: int = MERSENNE_PRIME_31) -> Dict[str, any]:
        """
        Verify that multiplier 'a' is a primitive root of Mersenne prime M31 = 2^31 - 1.
        According to the Primitive Root Theorem:
        a is a primitive root iff a^((m-1)/q) != 1 (mod m) for all prime divisors q of m - 1.
        Prime divisors of M31 - 1 = 2^31 - 2:
        q in {2, 3, 7, 11, 31, 151, 331}.
        """
        totient = m - 1
        prime_divisors = [2, 3, 7, 11, 31, 151, 331]
        test_results = {}
        is_primitive = True

        for q in prime_divisors:
            exponent = totient // q
            # Modular exponentiation
            val = pow(a, exponent, m)
            test_results[q] = {
                "exponent": f"(M31 - 1)/{q} = {exponent}",
                "residue": val,
                "passes_non_one_condition": (val != 1)
            }
            if val == 1:
                is_primitive = False

        return {
            "a": a,
            "m": m,
            "is_primitive_root": is_primitive,
            "max_period_length": m - 1,
            "prime_divisor_tests": test_results
        }

    @classmethod
    def check_hull_dobell(cls, a: int, c: int, m: int) -> Dict[str, any]:
        """
        Checks Hull-Dobell Theorem conditions for full period m (where c > 0):
        1. c and m are relatively prime: gcd(c, m) == 1
        2. a = 1 (mod p) for all prime factors p dividing m
        3. a = 1 (mod 4) if 4 divides m
        """
        cond1 = math.gcd(c, m) == 1
        
        # Factorize m to check condition 2
        temp_m = m
        primes = []
        d = 2
        while d * d <= temp_m:
            if temp_m % d == 0:
                primes.append(d)
                while temp_m % d == 0:
                    temp_m //= d
            d += 1
        if temp_m > 1:
            primes.append(temp_m)

        cond2 = all((a % p == 1) for p in primes)
        cond3 = (a % 4 == 1) if (m % 4 == 0) else True

        full_period = cond1 and cond2 and cond3
        return {
            "full_period": full_period,
            "cond1_gcd_c_m": cond1,
            "cond2_a_mod_p_equal_1": cond2,
            "cond3_a_mod_4_equal_1": cond3,
            "prime_factors_of_m": primes
        }


class VariateSampler:
    """
    Inverse Transform Method & Stochastic Variate Samplers.
    Converts uniform variates U ~ (0, 1) generated by LehmerLCG into targeted distributions.
    """
    def __init__(self, lcg: LehmerLCG):
        self.lcg = lcg

    def uniform(self, low: float = 0.0, high: float = 1.0) -> float:
        """Continuous uniform distribution U(low, high)."""
        u = self.lcg.next_uniform()
        return low + (high - low) * u

    def exponential(self, rate: float) -> float:
        """
        Exponential distribution with rate lambda (mean = 1/lambda).
        Derived via Inverse CDF:
        F(x) = 1 - e^(-lambda * x) = U  =>  X = -ln(1 - U) / lambda
        Since 1 - U is also Uniform(0, 1), X = -ln(U) / lambda.
        """
        if rate <= 0:
            raise ValueError("Rate lambda must be positive.")
        u = self.lcg.next_uniform()
        # Guard against zero log
        if u <= 0.0:
            u = 1e-10
        return -math.log(u) / rate

    def triangular(self, low: float, mode: float, high: float) -> float:
        """
        Triangular distribution Triangular(low, mode, high).
        Frequently used in maritime operations for docking maneuvers and inspection delays.
        """
        u = self.lcg.next_uniform()
        c = (mode - low) / (high - low)
        if u < c:
            return low + math.sqrt(u * (high - low) * (mode - low))
        else:
            return high - math.sqrt((1.0 - u) * (high - low) * (high - mode))

    def randint(self, low: int, high: int) -> int:
        """Discrete uniform integer in [low, high]."""
        u = self.lcg.next_uniform()
        return low + int(u * (high - low + 1))


class CRNStreamManager:
    """
    Common Random Numbers (CRN) & Independent Stream Manager.
    Allocates dedicated, non-overlapping LCG streams to prevent cross-component interference
    and guarantee rigorous variance reduction across comparative policy scenarios.
    """
    STREAM_STRIDE = 100_000  # Jump steps per logical stream

    def __init__(self, base_seed: int = 123456789):
        self.base_seed = base_seed
        self.streams: Dict[str, VariateSampler] = {}
        self._initialize_streams()

    def _initialize_streams(self):
        """Create distinct streams for arrivals, cargo, lightering, and maneuvers."""
        stream_keys = ["arrivals", "cargo", "lightering", "docking", "weather"]
        for idx, key in enumerate(stream_keys):
            # Advance state safely or use distinct modular seeds
            stream_seed = (self.base_seed + (idx + 1) * self.STREAM_STRIDE) % LehmerLCG.MERSENNE_PRIME_31
            if stream_seed == 0:
                stream_seed = 1
            lcg = LehmerLCG(seed=stream_seed, a=LehmerLCG.PARK_MILLER_A)
            self.streams[key] = VariateSampler(lcg)

    def get_stream(self, name: str) -> VariateSampler:
        """Retrieve a dedicated stream sampler by name."""
        if name not in self.streams:
            raise KeyError(f"Stream '{name}' not found. Available: {list(self.streams.keys())}")
        return self.streams[name]

    def reset_all(self):
        """Reset all streams back to their initial seeds for exact scenario replay."""
        for sampler in self.streams.values():
            sampler.lcg.reset()

